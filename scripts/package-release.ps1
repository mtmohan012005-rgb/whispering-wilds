$readmePath = Join-Path $stagingDir "README.txt"
[System.IO.File]::WriteAllText($readmePath, $readmeContent, [System.Text.Encoding]::UTF8)

# Create ZIP archive
$zipPath = Join-Path $resolvedReleasesDir $packageName
if (Test-Path $zipPath) {
    Remove-Item $zipPath -Force
}

Write-Host "Compressing release package to $zipPath ..." -ForegroundColor Yellow
Compress-Archive -Path (Join-Path $stagingDir "*") -DestinationPath $zipPath -CompressionLevel Optimal

# Remove temporary staging folder
Remove-Item -Path $stagingDir -Recurse -Force

# Verify ZIP contents
Add-Type -AssemblyName System.IO.Compression.FileSystem
$zip = [System.IO.Compression.ZipFile]::OpenRead($zipPath)
$hasExe = $false
$hasData = $false
foreach ($entry in $zip.Entries) {
    $norm = $entry.FullName.Replace('\', '/')
    if ($norm -eq "TheWhisperingWilds.exe") { $hasExe = $true }
    if ($norm.StartsWith("TheWhisperingWilds_Data/")) { $hasData = $true }
}
$entryCount = $zip.Entries.Count
$zip.Dispose()

if (-not $hasExe) {
    throw "Verification failed: TheWhisperingWilds.exe not found inside created ZIP archive!"
}
if (-not $hasData) {
    throw "Verification failed: TheWhisperingWilds_Data directory not found inside created ZIP archive!"
}
Write-Host "Verified ZIP structure ($entryCount entries, executable and data directory confirmed)." -ForegroundColor Green

# Calculate checksum and size using pure .NET SHA-256 helper
$zipItem = Get-Item $zipPath
$zipHash = Compute-FileSha256 -FilePath $zipPath
$sizeMB = [math]::Round($zipItem.Length / 1MB, 2)

$manifestData = [ordered]@{
    package = $packageName
    version = $cleanVersion
    candidate = $true
    target = "Windows x64"
    unityVersion = "6000.6.3f1"
    renderPipeline = "HDRP 17.7.0"
    testedCommit = $CommitSha
    codeCommit = $CommitSha
    headCommit = $gitHead
    isDirty = $isDirty
    status = $releaseStatus
    sizeBytes = $zipItem.Length
    sizeMB = $sizeMB
    sha256 = $zipHash
    generatedAt = (Get-Date).ToUniversalTime().ToString("o")
    scenesIncluded = 9
    scenes = @(
        "00_Boot",
        "01_StateMap_TamilNadu",
        "02_Chennai_GeorgeTown",
        "03_Pichavaram_Wetlands",
        "04_Thanjavur_Delta",
        "05_Chettinad_Mansion",
        "06_Mamallapuram_Shore",
        "07_Nilgiris_Sanctuary",
        "08_Ancient_Temple_Ruins"
    )
    testStatuses = [ordered]@{
        "unit_editmode" = "PASS_AUTOMATED"
        "playmode_gameplay" = "PASS_AUTOMATED"
        "backend_security" = "PASS_AUTOMATED"
        "gis_map_data" = "PASS_AUTOMATED"
        "server_cleanup" = "PASS_AUTOMATED"
        "interactive_walkthrough" = "NOT_TESTED_HUMAN"
    }
    blockers = [ordered]@{
        "firebase_cloud_sync" = "BLOCKED_CREDENTIALS"
        "authentic_field_audio" = "BLOCKED_EXTERNAL_ASSET"
        "live_two_client_multiplayer" = "NOT_TESTED"
    }
}

$manifestJson = $manifestData | ConvertTo-Json -Depth 5
$manifestPath = Join-Path $resolvedReleasesDir $manifestFileName
[System.IO.File]::WriteAllText($manifestPath, $manifestJson, [System.Text.Encoding]::UTF8)

Write-Host "`n============================================================" -ForegroundColor Green
Write-Host "RELEASE PACKAGE READY ($releaseStatus):" -ForegroundColor Green
Write-Host "File:       $($zipItem.FullName)" -ForegroundColor White
Write-Host "Size:       $sizeMB MB ($($zipItem.Length) bytes)" -ForegroundColor White
Write-Host "SHA-256:    $zipHash" -ForegroundColor White
Write-Host "Tested SHA: $CommitSha" -ForegroundColor White
Write-Host "Manifest:   $manifestPath" -ForegroundColor White
Write-Host "============================================================" -ForegroundColor Green
