======================================================================
Built with Unity 6000.6.3f1 (HDRP 17.7.0)
Target Platform: Windows 10/11 64-bit (Direct3D 11 / Direct3D 12)
Code Commit SHA: $CommitSha
Release Status: $releaseStatus

