# The Whispering Wilds - Automated Standalone Release Packager
param(
    [string]$BuildDir = "unity/Build/Windows",
    [string]$ReleasesDir = "artifacts/releases",
    [string]$CommitSha = "",
    [string]$Version = "1.0.1",
    [switch]$AllowDirty = $false
)

$ErrorActionPreference = "Stop"

# 0. Pure .NET Cryptographic Hash Helper (Zero module dependencies)
function Compute-FileSha256 {
    param([string]$FilePath)
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try {
        $stream = [System.IO.File]::OpenRead($FilePath)
        try {
            $bytes = $sha.ComputeHash($stream)
            return [System.BitConverter]::ToString($bytes).Replace("-", "").ToUpperInvariant()
        } finally {
            $stream.Close()
        }
    } finally {
        $sha.Dispose()
    }
}

# Release Version Safety Validation
if ([string]::IsNullOrWhiteSpace($Version)) {
    throw "Release safety error: Version parameter cannot be empty. Specify a valid candidate version such as '1.0.1'."
}
$cleanVersion = $Version.Trim()
if ($cleanVersion.StartsWith("v", [System.StringComparison]::OrdinalIgnoreCase)) {
    $cleanVersion = $cleanVersion.Substring(1)
}

if ($cleanVersion -eq "1.0.0") {
    throw "Release safety error: v1.0.0 is the published public release (SHA-256: 6F2D73A01F3DED83D632450C1341247ABE93F6CBFB0450C21926CEA4686A9A58). New candidate builds must target v1.0.1 or higher to prevent release provenance collision."
}

if ($cleanVersion -notmatch '^\d+\.\d+\.\d+(-[a-zA-Z0-9.]+)?$') {
    throw "Release safety error: Invalid semantic version format '$Version'. Expected format: X.Y.Z (e.g. 1.0.1)."
}

$packageName = "TheWhisperingWilds-v$cleanVersion-windows-x64.zip"
$stagingDirName = "TheWhisperingWilds-v$cleanVersion-windows-x64"
$manifestFileName = "RELEASE_MANIFEST-v$cleanVersion.json"

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$rootDir = (Resolve-Path (Join-Path $scriptDir "..")).Path

# 1. Resolve checked-out Git HEAD dynamically
$gitHead = (git -C $rootDir rev-parse HEAD 2>$null)
if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($gitHead)) {
    throw "Failed to resolve git HEAD from $rootDir"
}
$gitHead = $gitHead.Trim()

if (-not [string]::IsNullOrWhiteSpace($CommitSha)) {
    if ($CommitSha -notmatch '^[0-9a-fA-F]{40}$') {
        throw "Supplied CommitSha '$CommitSha' is not a valid 40-character hex SHA."
    }
    if ($CommitSha.ToLowerInvariant() -ne $gitHead.ToLowerInvariant()) {
        throw "Supplied CommitSha '$CommitSha' does not match actual git HEAD '$gitHead'. Refusing release creation on SHA mismatch."
    }
} else {
    $CommitSha = $gitHead
}

# 2. Check working tree cleanliness (excluding QA artifacts and audits generated by test runs)
$dirtySource = (git -C $rootDir status --porcelain 2>$null) | Where-Object {
    $_ -notmatch '^\s*[\?MADRCU?!]{1,2}\s+(artifacts|docs/audits)/'
}
$isDirty = (-not [string]::IsNullOrWhiteSpace($dirtySource))
if ($isDirty -and -not $AllowDirty) {
    throw "Git working tree has uncommitted source code changes. Refusing to package verified release without -AllowDirty. Uncommitted changes:`n$dirtySource"
}

$releaseStatus = if ($isDirty) { "UNVERIFIED_DIRTY" } else { "VERIFIED_CLEAN" }
Write-Host "Target Release Version: v$cleanVersion" -ForegroundColor Cyan
Write-Host "Target Code Revision:  $CommitSha ($releaseStatus)" -ForegroundColor Cyan

$resolvedBuildDir = Join-Path $rootDir $BuildDir
$resolvedReleasesDir = Join-Path $rootDir $ReleasesDir

if (!(Test-Path $resolvedBuildDir)) {
    throw "Build directory not found at $resolvedBuildDir"
}

# Check essential runtime build files
$requiredBuildFiles = @(
    "TheWhisperingWilds.exe",
    "UnityPlayer.dll",
    "UnityCrashHandler64.exe",
    "TheWhisperingWilds_Data",
    "MonoBleedingEdge"
)
foreach ($req in $requiredBuildFiles) {
    $p = Join-Path $resolvedBuildDir $req
    if (-not (Test-Path $p)) {
        throw "Missing required runtime build file or directory: $req at $p"
    }
}

if (!(Test-Path $resolvedReleasesDir)) {
    New-Item -ItemType Directory -Path $resolvedReleasesDir -Force | Out-Null
}

$stagingDir = Join-Path $resolvedReleasesDir $stagingDirName
if (Test-Path $stagingDir) {
    Remove-Item -Path $stagingDir -Recurse -Force
}
New-Item -ItemType Directory -Path $stagingDir -Force | Out-Null

Write-Host "Staging release files from $resolvedBuildDir..." -ForegroundColor Cyan

# Copy essential runtime files
Copy-Item (Join-Path $resolvedBuildDir "TheWhisperingWilds.exe") $stagingDir
Copy-Item (Join-Path $resolvedBuildDir "UnityPlayer.dll") $stagingDir
Copy-Item (Join-Path $resolvedBuildDir "UnityCrashHandler64.exe") $stagingDir

$optionalDlls = @("DirectML.dll", "dstorage.dll", "dstoragecore.dll")
foreach ($dll in $optionalDlls) {
    $src = Join-Path $resolvedBuildDir $dll
    if (Test-Path $src) {
        Copy-Item $src $stagingDir
    }
}

$d3d12Dir = Join-Path $resolvedBuildDir "D3D12"
if (Test-Path $d3d12Dir) {
    Copy-Item $d3d12Dir $stagingDir -Recurse
}

Copy-Item (Join-Path $resolvedBuildDir "TheWhisperingWilds_Data") $stagingDir -Recurse
Copy-Item (Join-Path $resolvedBuildDir "MonoBleedingEdge") $stagingDir -Recurse

# Add README.txt
$readmeContent = @"
======================================================================
